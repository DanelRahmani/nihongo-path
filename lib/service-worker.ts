/**
 * The service worker (H3), written by hand and served by the `force-static` route app/sw.js. The site works offline
 * for the practice pages and the pages already visited:
 * - on install, the home page, the practice pages and the data JSON are fetched into this build's page cache, and
 *   the build files each page names (`/_next/static/…`) into the build-file cache;
 * - pages and data are network-first: the network's answer is returned at once and kept afterwards, and the kept
 *   copy is used only when the network fails, so a new build is never hidden behind an old copy;
 * - build files are cache-first: their names change with their content, so they're kept across builds (and pruned
 *   to what the current build's pages name when a new worker activates);
 * - the page posts the build files it loaded before the worker took over, so the first visit's files are kept too;
 * - Next's router payloads (`.txt`, `?_rsc=`) and Range requests go to the network untouched (offline, the router
 *   falls back to loading the kept page);
 * - a page never visited, offline, gets a short offline notice.
 * Only same-origin GET requests are handled, and only whole 200 responses are kept. Pure: the source is a string,
 * so it can be tested.
 *
 * To take the worker off the site: set RETIRE_WORKER to true and deploy. That build's worker deletes the caches,
 * unregisters itself and reloads open tabs, and the page stops registering it. (Deleting the route would not do:
 * an update that fails leaves the installed worker running.)
 */

export const RETIRE_WORKER = false;

/** Fetched on install: the home page, the practice pages and the data they load. */
export const PRECACHE = [
  "/",
  "/kana/drill",
  "/kanji/drill",
  "/vocabulary",
  "/cloze",
  "/register",
  "/conjugation",
  "/review",
  "/type",
  "/placement",
  "/dictionary",
  "/data",
  "/dictionary-data.json",
  "/search-index.json",
  "/today-words.json",
  "/review-data.json",
  "/review-ids.json",
];

/** The cache names all start with this; anything else in Cache Storage is left alone. */
export const CACHE_PREFIX = "nihongo-path-";
/** Build files, kept across builds. */
export const STATIC_CACHE = `${CACHE_PREFIX}static`;

const OFFLINE_PAGE =
  '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' +
  "<title>Offline · Nihongo Path</title>" +
  '<body style="font:16px/1.6 system-ui,sans-serif;max-width:32rem;margin:4rem auto;padding:0 1rem">' +
  "<h1>You're offline</h1><p>This page hasn't been saved on this device yet. The practice pages, and pages you've opened since your last visit online, work offline.</p>" +
  '<p><a href="/">Go to the home page</a></p></body></html>';

/** The worker's source for one build. `version` names its page cache; plain ES2017, no imports. */
export function serviceWorkerSource(version: string, { precache = PRECACHE, retire = false }: { precache?: string[]; retire?: boolean } = {}): string {
  if (retire) {
    return `// Nihongo Path service worker, retired (build ${version}). Generated by lib/service-worker.ts.
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith(PREFIX)).map((key) => caches.delete(key))))
      .then(() => self.registration.unregister())
      .then(() => self.clients.matchAll({ type: "window" }))
      .then((clients) => Promise.all(clients.map((client) => client.navigate(client.url).catch(() => {})))),
  );
});
`;
  }
  return `// Nihongo Path service worker, build ${version}. Generated by lib/service-worker.ts.
const PAGES = ${JSON.stringify(`${CACHE_PREFIX}pages-${version}`)};
const STATIC = ${JSON.stringify(STATIC_CACHE)};
const PREFIX = ${JSON.stringify(CACHE_PREFIX)};
const PRECACHE = ${JSON.stringify(precache)};
const OFFLINE = ${JSON.stringify(OFFLINE_PAGE)};
// Where install records the build files this build's pages name, for pruning on activate.
const REFS = "/__build-files";

const keepable = (response) => response.status === 200 && response.type === "basic";
const buildFiles = (html) => [...new Set(html.match(/\\/_next\\/static\\/[^"'\\s\\\\)]+/g) || [])];

async function keepBuildFiles(urls) {
  const cache = await caches.open(STATIC);
  await Promise.all(urls.map(async (url) => {
    if (await cache.match(url)) return;
    const response = await fetch(url).catch(() => null);
    if (response && keepable(response)) await cache.put(url, response).catch(() => {});
  }));
}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const pages = await caches.open(PAGES);
    const files = [];
    // One missing file shouldn't stop the rest from being saved.
    await Promise.all(PRECACHE.map(async (url) => {
      const response = await fetch(url).catch(() => null);
      if (!response || !keepable(response)) return;
      if ((response.headers.get("Content-Type") || "").includes("text/html")) files.push(...buildFiles(await response.clone().text()));
      await pages.put(url, response).catch(() => {});
    }));
    await keepBuildFiles([...new Set(files)]);
    await pages.put(REFS, new Response(JSON.stringify(files))).catch(() => {});
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter((key) => key.startsWith(PREFIX) && key !== PAGES && key !== STATIC).map((key) => caches.delete(key)));
    // Build files no page of this build names are dropped, so the cache doesn't grow with every deploy.
    const refs = await (await caches.open(PAGES)).match(REFS);
    if (refs) {
      const wanted = new Set((await refs.json()).map((path) => new URL(path, self.location.origin).href));
      const cache = await caches.open(STATIC);
      const kept = await cache.keys();
      if (wanted.size) await Promise.all(kept.filter((request) => !wanted.has(request.url)).map((request) => cache.delete(request)));
    }
    await self.clients.claim();
  })());
});

// The page's own build files, loaded before this worker controlled it.
self.addEventListener("message", (event) => {
  const data = event.data;
  if (!data || data.type !== "keep" || !Array.isArray(data.urls)) return;
  const urls = data.urls.filter((url) => typeof url === "string" && new URL(url, self.location.origin).origin === self.location.origin && new URL(url, self.location.origin).pathname.startsWith("/_next/static/"));
  event.waitUntil(keepBuildFiles(urls));
});

async function networkFirst(event, key) {
  const cache = await caches.open(PAGES);
  let response;
  try {
    response = await fetch(event.request);
  } catch (error) {
    const kept = await cache.match(key);
    if (kept) return kept;
    if (event.request.mode === "navigate") return new Response(OFFLINE, { status: 503, headers: { "Content-Type": "text/html; charset=utf-8" } });
    throw error;
  }
  // Kept after the response is on its way: a failed save (a full quota) never costs the reader the page.
  if (keepable(response)) event.waitUntil(cache.put(key, response.clone()).catch(() => {}));
  return response;
}

async function cacheFirst(event) {
  const cache = await caches.open(STATIC);
  const kept = await cache.match(event.request);
  if (kept) return kept;
  const response = await fetch(event.request);
  if (keepable(response)) event.waitUntil(cache.put(event.request, response.clone()).catch(() => {}));
  return response;
}

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || request.headers.has("range")) return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname.startsWith("/_next/static/")) return event.respondWith(cacheFirst(event));
  // Router payloads change with the page they're asked from; the network serves them, and offline the router loads the page.
  if (url.searchParams.has("_rsc") || url.pathname.endsWith(".txt")) return;
  // A page is kept under its path alone (/dictionary?q=… is one entry), data under its full address.
  const key = request.mode === "navigate" ? url.origin + url.pathname : request.url;
  event.respondWith(networkFirst(event, key));
});
`;
}
